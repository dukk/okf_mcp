//! Build-time work:
//! - rebuilds the crate when a migration is added or edited (`sqlx::migrate!`
//!   embeds `migrations/` at compile time, and cargo would not notice a new
//!   file);
//! - embeds the web console (`src/http/ui/**`) as `$OUT_DIR/ui_assets.rs`, a
//!   table of `include_bytes!` that `src/http/ui.rs` pastes in with `include!`;
//! - embeds the mobile reader (`src/http/read/**`) the same way, as
//!   `$OUT_DIR/read_assets.rs` for `src/http/read.rs`.

use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    println!("cargo:rerun-if-changed=migrations");
    let manifest = env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    embed(
        &manifest,
        "src/http/ui",
        "ASSETS",
        &out_dir.join("ui_assets.rs"),
    );
    embed(
        &manifest,
        "src/http/read",
        "READ_ASSETS",
        &out_dir.join("read_assets.rs"),
    );
}

/// Writes `dest`: a `const <table>: &[(&str, &[u8])]` of every file under
/// `tree`, by its path below it, sorted so the binary is reproducible.
fn embed(manifest: &str, tree: &str, table: &str, dest: &Path) {
    // A directory here makes cargo rescan it recursively for changes.
    println!("cargo:rerun-if-changed={tree}");
    let root = Path::new(manifest).join(tree);
    let mut files = Vec::new();
    collect(&root, &root, &mut files);
    files.sort();
    let mut out = format!(
        "/// Every file under `{tree}`, by its path below it (generated by build.rs).\n\
         const {table}: &[(&str, &[u8])] = &[\n"
    );
    for (relative, absolute) in &files {
        out.push_str(&format!(
            "    ({relative:?}, include_bytes!({absolute:?})),\n"
        ));
    }
    out.push_str("];\n");
    fs::write(dest, out).expect("write an embedded asset table");
}

/// Appends `(path below root with '/' separators, absolute path)` for every
/// file under `dir`, recursively.
fn collect(root: &Path, dir: &Path, files: &mut Vec<(String, String)>) {
    for entry in fs::read_dir(dir).expect("read an embedded tree") {
        let path = entry.expect("read a directory entry").path();
        if path.is_dir() {
            collect(root, &path, files);
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .expect("a file below its tree")
            .to_string_lossy()
            .replace('\\', "/");
        files.push((relative, path.to_string_lossy().into_owned()));
    }
}
